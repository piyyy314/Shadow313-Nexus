TRAINING_SCRIPT = '''#!/usr/bin/env python3
"""
Shadow313 LoRA Fine-Tuning Script
Generated by Shadow313 NEXUS v4.0.0
"""
from unsloth import FastLanguageModel
from trl import SFTTrainer
from transformers import TrainingArguments
from datasets import load_dataset
import yaml, sys

def main():
    with open("finetune_config.yaml") as f:
        cfg = yaml.safe_load(f)

    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name     = cfg["model"]["base_model"],
        max_seq_length = cfg["model"]["max_seq_length"],
        dtype          = cfg["model"]["dtype"],
        load_in_4bit   = cfg["model"]["load_in_4bit"],
    )

    model = FastLanguageModel.get_peft_model(
        model,
        r                   = cfg["lora"]["r"],
        target_modules      = cfg["lora"]["target_modules"],
        lora_alpha          = cfg["lora"]["lora_alpha"],
        lora_dropout        = cfg["lora"]["lora_dropout"],
        bias                = cfg["lora"]["bias"],
        use_gradient_checkpointing = cfg["lora"]["use_gradient_checkpointing"],
        random_state        = cfg["lora"]["random_state"],
    )

    dataset = load_dataset("json", data_files=cfg["training"]["dataset"], split="train")

    trainer = SFTTrainer(
        model        = model,
        tokenizer    = tokenizer,
        train_dataset= dataset,
        dataset_text_field = "text",
        max_seq_length     = cfg["model"]["max_seq_length"],
        args = TrainingArguments(
            per_device_train_batch_size   = cfg["training"]["batch_size"],
            gradient_accumulation_steps   = cfg["training"]["gradient_accumulation_steps"],
            warmup_steps                  = cfg["training"]["warmup_steps"],
            max_steps                     = cfg["training"]["max_steps"],
            learning_rate                 = cfg["training"]["learning_rate"],
            fp16                          = cfg["training"]["fp16"],
            bf16                          = cfg["training"]["bf16"],
            logging_steps                 = cfg["training"]["logging_steps"],
            optim                         = cfg["training"]["optim"],
            weight_decay                  = cfg["training"]["weight_decay"],
            lr_scheduler_type             = cfg["training"]["lr_scheduler_type"],
            seed                          = cfg["training"]["seed"],
            output_dir                    = cfg["training"]["output_dir"],
        ),
    )

    print("Starting Shadow313 fine-tuning...")
    trainer.train()

    # Export to GGUF for Ollama
    model.save_pretrained_gguf(
        cfg["export"]["output_name"],
        tokenizer,
        quantization_method = cfg["export"]["quantization"],
    )
    print(f"Model exported: {cfg['export']['output_name']}.gguf")

    if cfg["export"]["ollama_import"]:
        import subprocess
        subprocess.run([
            "ollama", "create", cfg["export"]["ollama_model_name"],
            "-f", f"{cfg['export']['output_name']}.Modelfile"
        ])
        print(f"Ollama model created: {cfg['export']['ollama_model_name']}")

if __name__ == "__main__":
    main()
'''

