class FineTuneModule:
    """shadow313.v4.finetune_ui — LoRA fine-tuning config generator. Registered: finetune"""

    def __init__(self, kernel) -> None:
        self.kernel = kernel
        self.out    = kernel.out
        self.session= kernel.session

    def register(self, kernel) -> None:
        kernel.register("finetune", self.run)

    def run(
        self,
        generate_config: bool = False,
        dataset_path: str = "shadow313_training_data.jsonl",
        output_dir: str = "./shadow313-7b-output",
        generate_dataset: bool = False,
        dataset_size: int = 100,
    ) -> dict:
        self.out.section("SHADOW313 FINE-TUNE CONFIGURATION")
        result: dict[str, Any] = {}

        if generate_config:
            ts       = datetime.now(timezone.utc).isoformat()
            ts_short = datetime.now().strftime("%Y%m%d")
            config   = FINETUNE_CONFIG_TEMPLATE.format(
                timestamp       = ts,
                timestamp_short = ts_short,
                dataset_path    = dataset_path,
                output_dir      = output_dir,
            )
            config_path = Path("finetune_config.yaml")
            config_path.write_text(config)
            self.out.success(f"Config generated → {config_path}")

            script_path = Path("finetune.py")
            script_path.write_text(TRAINING_SCRIPT)
            self.out.success(f"Training script → {script_path}")

            result["config_path"] = str(config_path)
            result["script_path"] = str(script_path)
            self.out.info("Install deps: pip install unsloth trl datasets peft")
            self.out.info("Run training: python finetune.py")

        if generate_dataset:
            self.out.info(f"Generating {dataset_size} training examples …")
            examples = self._generate_training_data(dataset_size)
            ds_path  = Path(dataset_path)
            with open(ds_path, "w") as fh:
                for ex in examples:
                    fh.write(json.dumps(ex) + "\n")
            self.out.success(f"Dataset → {ds_path} ({len(examples)} examples)")
            result["dataset_path"] = str(ds_path)
            result["examples"]     = len(examples)

        return result

    def _generate_training_data(self, count: int) -> list[dict]:
        """Generate training examples from session findings using AI."""
        examples = [ALPACA_EXAMPLE]  # seed example

        findings = (self.session.read("findings.json") or {}).get("findings", [])
        for f in findings[:count]:
            cve  = f.get("cve", "")
            desc = f.get("description", "")
            if not cve or not desc:
                continue
            answer = self.kernel.ai.chat(
                f"Provide a detailed security analysis for {cve}: {desc[:200]}. "
                f"Include: risk level, attack vector, immediate actions, CVSS context.",
            )
            examples.append({
                "instruction": "Analyse this CVE and provide a risk assessment.",
                "input":       f"{cve}: {desc[:300]}",
                "output":      answer,
            })

        return examples[:count]