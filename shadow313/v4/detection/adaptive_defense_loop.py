# ── Data models ────────────────────────────────────────────────────────────────

@dataclass
class DetectionEvent:
    """Output from the LSTM ensemble — one fired alert."""
    event_id:    str
    head:        str          # ransomware_head | c2_head | etc.
    score:       float
    technique:   str
    host:        str
    timestamp:   str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    evaded:      bool = False  # True if red team bypassed detection


@dataclass
class RedTeamResult:
    """Output from one adversary emulation cycle."""
    run_id:          str
    persona:         str          # APT29 | APT41 | Lazarus | FIN7
    ttps_attempted:  list[str]
    ttps_detected:   list[str]
    ttps_evaded:     list[str]
    detection_rate:  float
    evasion_gaps:    list[str]    # specific blind spots found
    timestamp:       str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


@dataclass
class EvolvedRule:
    """A new or updated detection rule generated by the evolution engine."""
    rule_id:      str
    rule_type:    str          # SIGMA | LSTM_FEATURE | THRESHOLD_ADJUST
    technique:    str
    trigger:      str          # what gap triggered this rule
    rule_content: dict
    confidence:   float
    generated_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    deployed:     bool = False


@dataclass
class FusedIntelligence:
    """
    The 'delta' between what the blue team detected and what the red team
    actually did. This is the core signal for system evolution.
    """
    fusion_id:          str
    blue_detections:    int
    red_attempts:       int
    detection_rate:     float
    evasion_gaps:       list[str]
    high_risk_gaps:     list[str]   # gaps with CVSS-equivalent risk ≥ 7.0
    recommended_rules:  list[str]
    timestamp:          str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


# ── Blue Team: Detection Engine Interface ──────────────────────────────────────

class BlueTeamMonitor:
    """
    Wraps the LSTM ensemble + IR engine.
    In production: calls NexusDetectionEngine.process_log_entry()
    and IncidentResponseEngine.process_alert().
    Here: simulates realistic detection outcomes based on known coverage.
    """

    # Current detection rates per head (from our 100-threat test results)
    DETECTION_RATES = {
        "ransomware_head":       0.875,   # 87.5% — strong
        "lateral_movement_head": 0.923,   # 92.3% — strong
        "c2_head":               0.750,   # 75.0% — PhantomWire improved this
        "exfiltration_head":     0.600,   # 60.0% — GraveHound partially covers
    }

    # Known blind spots per ATT&CK technique (from coverage analysis)
    KNOWN_BLIND_SPOTS = {
        "T1055.012": "Process Hollowing — no child spawn, dim 32 zero signal",
        "T1195.002": "Supply Chain — signed cert bypasses trust chain",
        "T1021.002": "Pass-the-Ticket — no 4624 events, dim 34 never fires",
        "T1071.004": "DNS Tunneling — low-and-slow below threshold",
        "T1218":     "COM Object Hijacking — no child spawn, HKCU registry",
        "T1056.001": "Keylogging — requires EDR, not SIEM-detectable",
        "T1113":     "Screen Capture — requires EDR",
        "T1567.002": "Cloud Exfil — requires TI feed correlation",
    }

    def __init__(self):
        self.events_processed = 0
        self.detections: list[DetectionEvent] = []
        self.false_negatives: list[DetectionEvent] = []

    def process_telemetry_batch(self, events: list[dict]) -> list[DetectionEvent]:
        """
        Simulate LSTM ensemble processing a batch of log events.
        Returns fired alerts.
        """
        fired = []
        for event in events:
            head = event.get("head", "c2_head")
            technique = event.get("technique", "T1071")
            base_rate = self.DETECTION_RATES.get(head, 0.70)

            # Apply blind spot penalty
            if technique in self.KNOWN_BLIND_SPOTS:
                base_rate *= 0.30  # severe reduction for known blind spots

            score = random.gauss(base_rate, 0.08)
            score = max(0.0, min(1.0, score))
            threshold = {"ransomware_head": 0.55, "lateral_movement_head": 0.65,
                         "c2_head": 0.60, "exfiltration_head": 0.65}.get(head, 0.65)

            evt = DetectionEvent(
                event_id=f"EVT-{hashlib.md5(str(time.time_ns()).encode()).hexdigest()[:8].upper()}",
                head=head,
                score=score,
                technique=technique,
                host=event.get("host", "ws-unknown"),
                evaded=(score < threshold),
            )
            self.events_processed += 1

            if score >= threshold:
                self.detections.append(evt)
                fired.append(evt)
            else:
                self.false_negatives.append(evt)

        return fired

    def get_coverage_summary(self) -> dict:
        total = self.events_processed
        detected = len(self.detections)
        return {
            "total_processed": total,
            "detected":        detected,
            "missed":          len(self.false_negatives),
            "detection_rate":  detected / total if total > 0 else 0.0,
            "blind_spots":     list(self.KNOWN_BLIND_SPOTS.keys()),
        }


# ── Red Team: Adversary Emulation Engine ──────────────────────────────────────

class RedTeamEmulator:
    """
    Simulates adversary TTPs against the blue team's detection coverage.
    Maps to AtomicChain + AdversaryEmulator in Shadow313 tools.

    In production: calls shadow313.tools.purpleteam.atomicchain
    and shadow313.tools.purpleteam.coveragematrix.
    """

    # APT persona → TTP chains (from our Purple Team coverage analysis)
    PERSONAS = {
        "APT29": {
            "ttps": ["T1566.001", "T1059.001", "T1055", "T1003.001", "T1071.001",
                     "T1546.003", "T1021.002"],
            "evasion_style": "slow_and_deliberate",
            "baseline_coverage": 0.750,
        },
        "APT41": {
            "ttps": ["T1195.002", "T1574.002", "T1055.012", "T1003.006",
                     "T1071.004", "T1021.002"],
            "evasion_style": "supply_chain_focus",
            "baseline_coverage": 0.400,
        },
        "Lazarus": {
            "ttps": ["T1566.002", "T1059.001", "T1543.003", "T1558.003",
                     "T1071.004", "T1657"],
            "evasion_style": "aggressive_and_fast",
            "baseline_coverage": 0.714,
        },
        "FIN7": {
            "ttps": ["T1566.001", "T1204.002", "T1218", "T1552.001",
                     "T1056.001", "T1021.002"],
            "evasion_style": "lolbas_heavy",
            "baseline_coverage": 0.500,
        },
    }

    # Techniques that are currently undetectable (from coverage matrix)
    UNDETECTABLE = {
        "T1055.012", "T1195.002", "T1056.001", "T1113",
        "T1567.002", "T1218", "T1657",
    }

    def __init__(self, blue_monitor: BlueTeamMonitor):
        self.blue = blue_monitor
        self.results: list[RedTeamResult] = []

    def run_persona_simulation(self, persona_name: str) -> RedTeamResult:
        """
        Simulate one APT persona's full TTP chain against blue team coverage.
        """
        persona = self.PERSONAS.get(persona_name, self.PERSONAS["APT29"])
        ttps = persona["ttps"]

        detected = []
        evaded = []
        evasion_gaps = []

        for ttp in ttps:
            # Check if this TTP is in a known blind spot
            if ttp in self.UNDETECTABLE:
                evaded.append(ttp)
                evasion_gaps.append(
                    BlueTeamMonitor.KNOWN_BLIND_SPOTS.get(ttp, f"{ttp} — no detection rule")
                )
                continue

            # Simulate detection attempt
            head = self._ttp_to_head(ttp)
            base_rate = self.blue.DETECTION_RATES.get(head, 0.70)

            # Evasion style modifiers
            if persona["evasion_style"] == "slow_and_deliberate":
                base_rate *= 0.85  # timing jitter reduces detection
            elif persona["evasion_style"] == "supply_chain_focus":
                base_rate *= 0.60  # signed certs bypass trust
            elif persona["evasion_style"] == "lolbas_heavy":
                base_rate *= 0.75  # LOLBins reduce parent-child entropy signal

            if random.random() < base_rate:
                detected.append(ttp)
            else:
                evaded.append(ttp)
                evasion_gaps.append(f"{ttp} — evaded via {persona['evasion_style']}")

        detection_rate = len(detected) / len(ttps) if ttps else 0.0

        result = RedTeamResult(
            run_id=f"RED-{hashlib.md5(f'{persona_name}{time.time_ns()}'.encode()).hexdigest()[:8].upper()}",
            persona=persona_name,
            ttps_attempted=ttps,
            ttps_detected=detected,
            ttps_evaded=evaded,
            detection_rate=detection_rate,
            evasion_gaps=evasion_gaps,
        )
        self.results.append(result)
        return result

    def _ttp_to_head(self, ttp: str) -> str:
        """Map ATT&CK technique to LSTM head."""
        mapping = {
            "T1486": "ransomware_head", "T1490": "ransomware_head",
            "T1485": "ransomware_head", "T1489": "ransomware_head",
            "T1021": "lateral_movement_head", "T1021.002": "lateral_movement_head",
            "T1021.006": "lateral_movement_head", "T1558.003": "lateral_movement_head",
            "T1071": "c2_head", "T1071.001": "c2_head",
            "T1071.004": "c2_head", "T1543.003": "c2_head",
            "T1041": "exfiltration_head", "T1567.002": "exfiltration_head",
            "T1657": "exfiltration_head",
        }
        for prefix, head in mapping.items():
            if ttp.startswith(prefix):
                return head
        return "c2_head"  # default

    def get_aggregate_gaps(self) -> list[str]:
        """Return all unique evasion gaps across all red team runs."""
        all_gaps = []
        for result in self.results:
            all_gaps.extend(result.evasion_gaps)
        return list(set(all_gaps))


# ── Intelligence Fusion Engine ─────────────────────────────────────────────────

class IntelligenceFusion:
    """
    The 'QDMA delta' — computes the gap between what blue detected
    and what red actually did. This is the signal for rule evolution.

    Maps to: YSDF.QDMA.process_all_data() in the AQC-Core architecture.
    No quantum annealing required — this is a set-difference operation.
    """

    # Risk scores for each evasion gap (technique → risk 0-10)
    GAP_RISK_SCORES = {
        "T1055.012": 9.5,  # Process Hollowing — critical
        "T1195.002": 9.8,  # Supply Chain — critical
        "T1021.002": 8.5,  # Pass-the-Ticket — high
        "T1071.004": 7.8,  # DNS Tunneling — high
        "T1218":     7.5,  # COM Hijacking — high
        "T1056.001": 6.5,  # Keylogging — medium (requires EDR)
        "T1113":     5.5,  # Screen Capture — medium
        "T1567.002": 8.0,  # Cloud Exfil — high
    }

    def fuse(self, blue: BlueTeamMonitor, red: RedTeamEmulator) -> FusedIntelligence:
        """Compute the delta between blue coverage and red evasion."""
        blue_summary = blue.get_coverage_summary()
        all_gaps = red.get_aggregate_gaps()

        # Extract technique IDs from gap descriptions
        gap_techniques = []
        for gap in all_gaps:
            for ttp in BlueTeamMonitor.KNOWN_BLIND_SPOTS:
                if ttp in gap:
                    gap_techniques.append(ttp)

        # Identify high-risk gaps (risk ≥ 7.0)
        high_risk = [
            t for t in gap_techniques
            if self.GAP_RISK_SCORES.get(t, 0) >= 7.0
        ]

        # Generate rule recommendations
        recommendations = self._recommend_rules(gap_techniques)

        return FusedIntelligence(
            fusion_id=f"FUSE-{hashlib.md5(str(time.time_ns()).encode()).hexdigest()[:8].upper()}",
            blue_detections=blue_summary["detected"],
            red_attempts=sum(len(r.ttps_attempted) for r in red.results),
            detection_rate=blue_summary["detection_rate"],
            evasion_gaps=all_gaps,
            high_risk_gaps=high_risk,
            recommended_rules=recommendations,
        )

    def _recommend_rules(self, gap_techniques: list[str]) -> list[str]:
        """Map evasion gaps to specific rule recommendations."""
        rule_map = {
            "T1055.012": "Add Sysmon Event 7 unsigned DLL load monitoring + Event 8 CreateRemoteThread",
            "T1195.002": "Add certificate subject vs. vendor folder mismatch detection",
            "T1021.002": "Add Event 4648 explicit credential use + WSMan PSRemoting correlation",
            "T1071.004": "Remove rate threshold; add structural DNS label analysis (count + max length)",
            "T1218":     "Add HKCU CLSID InprocServer32 registration monitoring",
            "T1056.001": "Requires EDR integration — out of SIEM scope",
            "T1113":     "Requires EDR integration — out of SIEM scope",
            "T1567.002": "Add TI feed correlation for cloud storage upload anomalies",
        }
        return [rule_map[t] for t in gap_techniques if t in rule_map]


