#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Shadow313 NEXUS — Complete Laptop Fix Script
    Fixes: watchdog errors, OLLAMA_HOST, profile, WSL2, Docker, accounts

.DESCRIPTION
    Run this in PowerShell 7 (normal user, NOT admin) from shadow313-nexus folder.
    For steps requiring admin, it will tell you exactly what to run.

.EXAMPLE
    cd C:\Users\shiatoali\shadow313-nexus
    Set-ExecutionPolicy -Scope Process -ExecutionPolicy Bypass
    .\scripts\fix-laptop-complete.ps1
#>

param(
    [switch]$AdminMode,   # Run admin-only fixes (run as admin)
    [switch]$CheckOnly    # Only report, don't fix
)

$ErrorActionPreference = "Continue"
$repo = "C:\Users\shiatoali\shadow313-nexus"
$user = $env:USERNAME

function Write-Header { param([string]$t) Write-Host "`n╔══ $t ══╗" -ForegroundColor Cyan }
function Write-OK     { param([string]$m) Write-Host "  ✅ $m" -ForegroundColor Green }
function Write-Fix    { param([string]$m) Write-Host "  🔧 $m" -ForegroundColor Magenta }
function Write-Warn   { param([string]$m) Write-Host "  ⚠️  $m" -ForegroundColor Yellow }
function Write-Fail   { param([string]$m) Write-Host "  ❌ $m" -ForegroundColor Red }
function Write-Info   { param([string]$m) Write-Host "  ℹ️  $m" -ForegroundColor Gray }

Write-Host @"

╔══════════════════════════════════════════════════════════════════╗
║  Shadow313 NEXUS — Complete Laptop Fix                         ║
║  Fixes watchdog errors, profile, Ollama, WSL2, Docker          ║
╚══════════════════════════════════════════════════════════════════╝
"@ -ForegroundColor Cyan

# ─────────────────────────────────────────────────────────────────
# STEP 1: READ WATCHDOG LOG — IDENTIFY THE 2 CRITICAL ISSUES
# ─────────────────────────────────────────────────────────────────
Write-Header "STEP 1: Watchdog Log Analysis"

$logFile = "$repo\logs\watchdog-2026-11.log"
if (Test-Path $logFile) {
    Write-OK "Watchdog log found"
    $logContent = Get-Content $logFile -Tail 100
    $criticals = $logContent | Where-Object { $_ -match "\[FAIL\]|\[CRITICAL\]" }
    $warnings  = $logContent | Where-Object { $_ -match "\[WARN\]" }
    
    Write-Host "`n  CRITICAL ISSUES:" -ForegroundColor Red
    if ($criticals) {
        $criticals | ForEach-Object { Write-Host "    $_" -ForegroundColor Red }
    } else {
        Write-Host "    (none found in last 100 lines)" -ForegroundColor Gray
    }
    
    Write-Host "`n  WARNINGS:" -ForegroundColor Yellow
    if ($warnings) {
        $warnings | Select-Object -First 10 | ForEach-Object { Write-Host "    $_" -ForegroundColor Yellow }
    }
} else {
    Write-Warn "Watchdog log not found at $logFile"
    Write-Info "Run: .\shadow313-watchdog.ps1 -Check to generate it"
}

# ─────────────────────────────────────────────────────────────────
# STEP 2: FIX POWERSHELL PROFILE (OLLAMA_HOST + start dir)
# ─────────────────────────────────────────────────────────────────
Write-Header "STEP 2: Fix PowerShell Profile"

# Find the actual profile path
$profilePaths = @(
    $PROFILE,
    "$env:USERPROFILE\Documents\PowerShell\Microsoft.PowerShell_profile.ps1",
    "$env:USERPROFILE\OneDrive\Desktop\Documents\PowerShell\Microsoft.PowerShell_profile.ps1",
    "$env:USERPROFILE\OneDrive\Documents\PowerShell\Microsoft.PowerShell_profile.ps1"
)

$profilePath = $null
foreach ($p in $profilePaths) {
    if (Test-Path $p) { $profilePath = $p; break }
}

if (-not $profilePath) {
    # Create in standard location
    $profilePath = "$env:USERPROFILE\Documents\PowerShell\Microsoft.PowerShell_profile.ps1"
    New-Item -ItemType Directory -Path (Split-Path $profilePath) -Force | Out-Null
    Write-Fix "Creating new profile at: $profilePath"
} else {
    Write-OK "Profile found: $profilePath"
}

$profileContent = Get-Content $profilePath -Raw -ErrorAction SilentlyContinue

# Check for issues
$hasOllamaHost = $profileContent -match "OLLAMA_HOST"
$hasSystem32   = $profileContent -match "System32"
$hasHomeDir    = $profileContent -match "Set-Location.*USERPROFILE|cd.*USERPROFILE|Set-Location.*~"

Write-Host "  Profile checks:" -ForegroundColor Gray
Write-Host "    OLLAMA_HOST present: $hasOllamaHost" -ForegroundColor $(if($hasOllamaHost){"Green"}else{"Red"})
Write-Host "    System32 (bad):      $hasSystem32"   -ForegroundColor $(if($hasSystem32){"Red"}else{"Green"})
Write-Host "    Home dir set:        $hasHomeDir"    -ForegroundColor $(if($hasHomeDir){"Green"}else{"Yellow"})

if (-not $CheckOnly) {
    # Build the clean profile
    $cleanProfile = @'
# ═══════════════════════════════════════════════════════════════
#  Shadow313 NEXUS — PowerShell 7 Profile
#  Auto-generated by fix-laptop-complete.ps1
# ═══════════════════════════════════════════════════════════════

# ── Start in home directory (NOT System32) ───────────────────────
Set-Location $env:USERPROFILE

# ── Ollama environment variables ─────────────────────────────────
$env:OLLAMA_HOST              = "0.0.0.0:11434"
$env:OLLAMA_ORIGINS           = "http://localhost,http://127.0.0.1,http://host.docker.internal,app://"
$env:OLLAMA_NUM_PARALLEL      = "2"
$env:OLLAMA_NUM_CTX           = "8192"
$env:OLLAMA_KEEP_ALIVE        = "10m"
$env:OLLAMA_MAX_LOADED_MODELS = "2"
$env:OLLAMA_DEBUG             = "0"

# ── Prompt ───────────────────────────────────────────────────────
function prompt {
    $loc = (Get-Location).Path.Replace($env:USERPROFILE, "~")
    $branch = ""
    try {
        $b = git branch --show-current 2>$null
        if ($b) { $branch = " ($b)" }
    } catch {}
    Write-Host "⬡ shadow313$branch $loc ❯" -NoNewline -ForegroundColor Green
    return " "
}

# ── Navigation aliases ────────────────────────────────────────────
function s313   { Set-Location "$env:USERPROFILE\shadow313-nexus" }
function ubuntu { wsl -d Ubuntu-24.04 }
function kali   { wsl -d kali-linux }
function dps    { docker ps --format "table {{.Names}}\t{{.Status}}\t{{.Ports}}" }
function sysinfo {
    Write-Host "RAM: $([math]::Round((Get-CimInstance Win32_OperatingSystem).FreePhysicalMemory/1MB,1))GB free" -ForegroundColor Cyan
    Write-Host "CPU: $((Get-CimInstance Win32_Processor).LoadPercentage)%" -ForegroundColor Cyan
}

# ── Ollama shortcuts ──────────────────────────────────────────────
function ollama-status {
    try {
        $r = Invoke-RestMethod "http://127.0.0.1:11434/api/tags" -TimeoutSec 3
        Write-Host "✅ Ollama: $($r.models.Count) models" -ForegroundColor Green
        $r.models | ForEach-Object { Write-Host "   • $($_.name)" -ForegroundColor Cyan }
    } catch {
        Write-Host "❌ Ollama not responding" -ForegroundColor Red
    }
}

# ── Auto-start Ollama silently ────────────────────────────────────
if (-not (Get-Process -Name "ollama" -ErrorAction SilentlyContinue)) {
    Start-Process ollama -ArgumentList "serve" -WindowStyle Hidden -ErrorAction SilentlyContinue
}

# ── Welcome ───────────────────────────────────────────────────────
Write-Host ""
Write-Host "  ⬡ Shadow313 NEXUS  |  PS $($PSVersionTable.PSVersion.Major).$($PSVersionTable.PSVersion.Minor)  |  $env:USERNAME" -ForegroundColor Green
$repoOk  = if (Test-Path "$env:USERPROFILE\shadow313-nexus\.git") { "✅" } else { "❌" }
$ollamaOk = if (Get-Process -Name "ollama" -ErrorAction SilentlyContinue) { "✅" } else { "⚠️" }
$dockerOk = if (Get-Command docker -ErrorAction SilentlyContinue) { "✅" } else { "❌" }
Write-Host "  Repo $repoOk  Ollama $ollamaOk  Docker $dockerOk" -ForegroundColor Gray
Write-Host "  Commands: s313, ubuntu, kali, ollama-status, dps, sysinfo" -ForegroundColor DarkGray
Write-Host ""
'@

    Set-Content -Path $profilePath -Value $cleanProfile -Encoding UTF8
    Write-Fix "Profile rewritten: OLLAMA_HOST added, System32 removed, home dir set"
    Write-OK "Profile saved to: $profilePath"
    
    # Also set OLLAMA_HOST permanently in registry
    [System.Environment]::SetEnvironmentVariable("OLLAMA_HOST", "0.0.0.0:11434", "User")
    [System.Environment]::SetEnvironmentVariable("OLLAMA_ORIGINS", "http://localhost,http://127.0.0.1,http://host.docker.internal,app://", "User")
    [System.Environment]::SetEnvironmentVariable("OLLAMA_NUM_PARALLEL", "2", "User")
    [System.Environment]::SetEnvironmentVariable("OLLAMA_NUM_CTX", "8192", "User")
    [System.Environment]::SetEnvironmentVariable("OLLAMA_KEEP_ALIVE", "10m", "User")
    Write-Fix "OLLAMA_HOST set permanently in User environment variables"
}

# ─────────────────────────────────────────────────────────────────
# STEP 3: FIX WINDOWS TERMINAL (hide old profiles, PS7 default)
# ─────────────────────────────────────────────────────────────────
Write-Header "STEP 3: Fix Windows Terminal"

$wtPaths = @(
    "$env:LOCALAPPDATA\Packages\Microsoft.WindowsTerminal_8wekyb3d8bbwe\LocalState\settings.json",
    "$env:LOCALAPPDATA\Microsoft\Windows Terminal\settings.json"
)
$wtPath = $wtPaths | Where-Object { Test-Path $_ } | Select-Object -First 1

if ($wtPath -and -not $CheckOnly) {
    $wt = Get-Content $wtPath | ConvertFrom-Json -AsHashtable
    
    # Find PS7 GUID
    $ps7Guid = "{574e775e-4f2a-5b96-ac1e-a2962a402336}"
    $ps7Profile = $wt.profiles.list | Where-Object { $_.name -match "PowerShell 7" -or $_.commandline -match "pwsh" } | Select-Object -Last 1
    if ($ps7Profile) { $ps7Guid = $ps7Profile.guid }
    
    # Set default to PS7
    $wt["defaultProfile"] = $ps7Guid
    
    # Hide old profiles
    $hideNames = @("Windows PowerShell", "Command Prompt", "PowerShell", "Developer Command Prompt", "Developer PowerShell")
    foreach ($profile in $wt.profiles.list) {
        if ($hideNames | Where-Object { $profile.name -match $_ }) {
            $profile["hidden"] = $true
        }
    }
    
    # Set PS7 start directory
    foreach ($profile in $wt.profiles.list) {
        if ($profile.guid -eq $ps7Guid) {
            $profile["startingDirectory"] = "%USERPROFILE%"
            $profile["hidden"] = $false
        }
    }
    
    $wt | ConvertTo-Json -Depth 20 | Set-Content $wtPath -Encoding UTF8
    Write-Fix "Windows Terminal: PS7 set as default, old profiles hidden, start dir fixed"
} elseif ($wtPath) {
    Write-OK "Windows Terminal settings found (check-only mode)"
} else {
    Write-Warn "Windows Terminal settings not found"
}

# ─────────────────────────────────────────────────────────────────
# STEP 4: FIX WSL2 DNS
# ─────────────────────────────────────────────────────────────────
Write-Header "STEP 4: Fix WSL2 DNS"

# Fix .wslconfig
$wslConfig = @"
[wsl2]
memory=4GB
processors=2
swap=2GB
networkingMode=mirrored
dnsTunneling=true
firewall=true
"@

if (-not $CheckOnly) {
    Set-Content "$env:USERPROFILE\.wslconfig" $wslConfig -Encoding UTF8
    Write-Fix ".wslconfig updated (4GB RAM, mirrored networking)"
}

# Fix Ubuntu DNS
$ubuntuOk = wsl -d Ubuntu-24.04 -- echo "ok" 2>$null
if ($ubuntuOk -match "ok") {
    Write-OK "Ubuntu-24.04 accessible"
    if (-not $CheckOnly) {
        wsl -d Ubuntu-24.04 -- bash -c "sudo rm -f /etc/resolv.conf; printf 'nameserver 9.9.9.9\nnameserver 8.8.8.8\n' | sudo tee /etc/resolv.conf > /dev/null; echo 'Acquire::ForceIPv4 true;' | sudo tee /etc/apt/apt.conf.d/99force-ipv4 > /dev/null" 2>$null
        Write-Fix "Ubuntu DNS fixed (9.9.9.9)"
    }
} else {
    Write-Warn "Ubuntu-24.04 not accessible — run: wsl --install -d Ubuntu-24.04"
}

$kaliOk = wsl -d kali-linux -- echo "ok" 2>$null
if ($kaliOk -match "ok") {
    Write-OK "Kali Linux accessible"
    if (-not $CheckOnly) {
        wsl -d kali-linux -- bash -c "sudo rm -f /etc/resolv.conf; printf 'nameserver 9.9.9.9\nnameserver 8.8.8.8\n' | sudo tee /etc/resolv.conf > /dev/null" 2>$null
        Write-Fix "Kali DNS fixed (9.9.9.9)"
    }
} else {
    Write-Warn "Kali Linux not accessible — run: wsl --install -d kali-linux"
}

# ─────────────────────────────────────────────────────────────────
# STEP 5: FIX OLLAMA
# ─────────────────────────────────────────────────────────────────
Write-Header "STEP 5: Fix Ollama"

$ollamaRunning = Get-Process -Name "ollama" -ErrorAction SilentlyContinue
if ($ollamaRunning) {
    Write-OK "Ollama running (PID $($ollamaRunning.Id))"
} else {
    if (-not $CheckOnly) {
        Start-Process ollama -ArgumentList "serve" -WindowStyle Hidden -ErrorAction SilentlyContinue
        Start-Sleep 3
        Write-Fix "Ollama started silently"
    }
}

try {
    $models = Invoke-RestMethod "http://127.0.0.1:11434/api/tags" -TimeoutSec 5
    Write-OK "Ollama API responding — $($models.models.Count) models"
    $models.models | ForEach-Object { Write-Info "  Model: $($_.name)" }
} catch {
    Write-Warn "Ollama API not responding on port 11434"
    Write-Info "  Check: OLLAMA_HOST=$env:OLLAMA_HOST"
}

# ─────────────────────────────────────────────────────────────────
# STEP 6: FIX DOCKER / OPEN WEBUI
# ─────────────────────────────────────────────────────────────────
Write-Header "STEP 6: Fix Docker / Open WebUI"

$dockerRunning = Get-Process -Name "com.docker.backend" -ErrorAction SilentlyContinue
if ($dockerRunning) {
    Write-OK "Docker Desktop running"
    
    $owStatus = docker ps --filter "name=open-webui" --format "{{.Status}}" 2>$null
    if ($owStatus -match "Up") {
        Write-OK "Open WebUI: $owStatus → http://localhost:3000"
    } else {
        Write-Warn "Open WebUI not running"
        if (-not $CheckOnly) {
            Write-Info "Starting Open WebUI..."
            docker run -d `
                -p 3000:8080 `
                --add-host=host.docker.internal:host-gateway `
                -e OLLAMA_BASE_URL=http://host.docker.internal:11434 `
                -v open-webui:/app/backend/data `
                --name open-webui `
                --restart always `
                ghcr.io/open-webui/open-webui:main 2>$null
            Write-Fix "Open WebUI container started → http://localhost:3000"
        }
    }
} else {
    Write-Warn "Docker Desktop not running — open it manually"
}

# ─────────────────────────────────────────────────────────────────
# STEP 7: ACCOUNT AUDIT
# ─────────────────────────────────────────────────────────────────
Write-Header "STEP 7: Account Audit"

$accounts = Get-LocalUser
foreach ($acct in $accounts) {
    $inAdmin = (Get-LocalGroupMember -Group "Administrators" -ErrorAction SilentlyContinue) | Where-Object { $_.Name -match $acct.Name }
    $status = if ($acct.Enabled) { "ENABLED" } else { "disabled" }
    $adminFlag = if ($inAdmin) { " [ADMIN]" } else { "" }
    $color = if ($acct.Name -eq $user) { "Green" } elseif ($acct.Enabled -and $acct.Name -ne "WDAGUtilityAccount") { "Yellow" } else { "Gray" }
    Write-Host "  $status $($acct.Name)$adminFlag" -ForegroundColor $color
}

Write-Host ""
Write-Warn "Baalb account: If enabled + in Admins, it can contaminate shiatoali via OneDrive"
Write-Info "To disable Baalb (run as Admin): Disable-LocalUser -Name 'Baalb'"
Write-Info "To remove from Admins (run as Admin): Remove-LocalGroupMember -Group 'Administrators' -Member 'Baalb'"

# ─────────────────────────────────────────────────────────────────
# STEP 8: GIT REPO STATUS
# ─────────────────────────────────────────────────────────────────
Write-Header "STEP 8: Git Repo Status"

if (Test-Path "$repo\.git") {
    Push-Location $repo
    $behind = git rev-list HEAD..origin/master --count 2>$null
    $ahead  = git rev-list origin/master..HEAD --count 2>$null
    $dirty  = git status --short 2>$null
    
    if ($behind -gt 0) { Write-Warn "Repo is $behind commits BEHIND origin — run: git pull origin master" }
    else { Write-OK "Repo is up to date with origin" }
    
    if ($ahead -gt 0) { Write-Warn "Repo is $ahead commits AHEAD — run: git push origin master" }
    
    if ($dirty) {
        Write-Warn "Uncommitted changes:"
        $dirty | ForEach-Object { Write-Host "    $_" -ForegroundColor Yellow }
    } else {
        Write-OK "Working tree clean"
    }
    Pop-Location
} else {
    Write-Fail "Repo not found at $repo"
}

